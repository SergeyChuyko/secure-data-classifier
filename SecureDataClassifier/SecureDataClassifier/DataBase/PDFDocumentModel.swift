extension PDFGenerator {
    static func generate(from model: PDFDocumentModel) -> Data {
        let pageRect = CGRect(x: 0, y: 0, width: 595, height: 842) // A4
        let format = UIGraphicsPDFRendererFormat()
        let renderer = UIGraphicsPDFRenderer(bounds: pageRect, format: format)

        let data = renderer.pdfData { context in
            // --- Название ИС
            context.beginPage()
            let titleAttributes: [NSAttributedString.Key: Any] = [
                .font: UIFont.systemFont(ofSize: 28, weight: .bold)
            ]
            model.systemData.systemName.draw(in: CGRect(x: 40, y: 60, width: pageRect.width - 80, height: 50),
                                             withAttributes: titleAttributes)

            // --- Длинный текст (introText, много страниц)
            let textAttributes: [NSAttributedString.Key: Any] = [
                .font: UIFont.systemFont(ofSize: 16)
            ]
            let textRect = CGRect(x: 40, y: 120, width: pageRect.width - 80, height: pageRect.height - 160)
            let attributedText = NSAttributedString(string: model.introText, attributes: textAttributes)

            let framesetter = CTFramesetterCreateWithAttributedString(attributedText)
            var currentRange = CFRangeMake(0, 0)

            repeat {
                context.beginPage()
                let path = CGMutablePath()
                path.addRect(textRect)
                let frame = CTFramesetterCreateFrame(framesetter, currentRange, path, nil)
                let frameRange = CTFrameGetVisibleStringRange(frame)
                CTFrameDraw(frame, context.cgContext)
                currentRange.location += frameRange.length
            } while currentRange.location < attributedText.length

            // --- Последняя страница: данные из SystemDataModel
            context.beginPage()
            let bodyText = """
            Категория: \(model.systemData.category)
            Количество субъектов: \(model.systemData.subjectsCount)
            Цель обработки: \(model.systemData.purpose)
            Доступ: \(model.systemData.access)
            Способы доступа: \(model.systemData.accessWay)
            """

            bodyText.draw(in: CGRect(x: 40, y: 60, width: pageRect.width - 80, height: 300),
                          withAttributes: textAttributes)

            // --- Подпись
            let footerAttributes: [NSAttributedString.Key: Any] = [
                .font: UIFont.systemFont(ofSize: 16, weight: .medium)
            ]
            model.footer.draw(in: CGRect(x: 40, y: pageRect.height - 100, width: pageRect.width - 80, height: 40),
                              withAttributes: footerAttributes)
        }

        return data
    }
}
