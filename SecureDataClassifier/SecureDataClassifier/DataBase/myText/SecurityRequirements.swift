import Foundation

/// Descriptions of security requirements for personal data protection levels.
struct SecurityRequirements {
    /// Requirements text for ensuring 1st level of protection of personal data.
    static let level1: String = """
Для обеспечения 1-го уровня защищённости персональных данных при их обработке в информационной системе необходимо выполнение следующих требований:

а) автоматическая регистрация в электронном журнале безопасности изменения полномочий сотрудника оператора по доступу к персональным данным, содержащимся в информационной системе;

б) создание отдельного структурного подразделения, ответственного за обеспечение безопасности персональных данных в информационной системе, либо возложение этих функций на одно из существующих подразделений оператора.

Помимо указанных дополнительных мер, должны быть выполнены требования, установленные для 2-го и 3-го уровней защищённости (включая назначение ответственного за безопасность, контроль доступа к журналам безопасности, физическую защиту помещений, сохранность носителей, ограничение доступа к персональным данным и применение сертифицированных средств защиты информации при необходимости).
"""

    /// Requirements text for ensuring 2nd level of protection of personal data.
    static let level2: String = """
Для обеспечения 2-го уровня защищённости персональных данных при их обработке в информационной системе, помимо выполнения требований, предусмотренных для 3-го уровня защищённости, необходимо обеспечить дополнительное условие:

– доступ к содержанию электронного журнала регистрации событий безопасности (audit log) должен предоставляться исключительно тем должностным лицам (работникам) оператора или уполномоченного лица, которым сведения из этого журнала необходимы для выполнения их служебных обязанностей.

Таким образом, для 2-го уровня, наряду с выполнением всех мер, требуемых для 3-го уровня (режим защиты помещений, сохранность носителей, назначение ответственного и т.д.), вводится ограничение доступа к журналам безопасности исключительно для уполномоченных сотрудников.
"""

    /// Requirements text for ensuring 3rd level of protection of personal data.
    static let level3: String = """
Для обеспечения 3-го уровня защищённости персональных данных при их обработке в информационной системе необходимо выполнение следующих базовых организационных мер:

а) организация режима безопасности помещений, в которых размещена ИСПДн, предотвращающего неконтролируемый доступ посторонних лиц (например, оснащение помещений замками на дверях, учет и контроль доступа, опечатывание помещений после работы);

б) обеспечение сохранности носителей персональных данных (хранение съёмных носителей в сейфах или металлических шкафах, учет носителей в журнале и т.д.);

в) утверждение руководителем оператора перечня лиц, чьи служебные обязанности требуют доступа к персональным данным, обрабатываемым в данной информационной системе (разграничение доступа по должностным обязанностям);

г) использование средств защиты информации, прошедших в установленном порядке оценку соответствия требованиям законодательства РФ в области безопасности информации, в случаях, когда применение таких средств необходимо для нейтрализации актуальных угроз.

д) назначение должностного лица, ответственного за обеспечение безопасности персональных данных в ИСПДн (приказом по организации должен быть определён ответственный за безопасность ПДн).

Перечисленные требования установлены постановлением Правительства РФ №1119 и обязательны для реализации в рамках 3-го уровня защищённости. 
"""
    
    static let defaultBlock: String = """
  Согласно требованиям законодательства РФ и постановлению Правительства №1119, при обработке персональных данных в информационных системах должны быть реализованы следующие организационные и технические меры:

  • Назначение ответственного за организацию обработки и защиту персональных данных;
  • Ограничение доступа сотрудников к персональным данным, строго в пределах их служебных обязанностей;
  • Разработка и утверждение локальных актов, регулирующих порядок обработки и защиты персональных данных;
  • Проведение оценки вреда субъектам ПДн в случае нарушения безопасности данных;
  • Применение средств антивирусной защиты, межсетевого экранирования, системы обнаружения вторжений;
  • Применение средств криптографической защиты (при необходимости);
  • Ведение журналов учёта действий пользователей, связанных с обработкой ПДн;
  • Проведение регулярных проверок эффективности применяемых мер защиты;
  • Проведение обучения работников, допущенных к обработке ПДн, по вопросам информационной безопасности;
  • Реализация физической защиты помещений, где размещается ИСПДн.

  Все указанные меры обязательны к реализации вне зависимости от уровня защищённости, с учётом актуальных угроз и категорий обрабатываемых данных.
  """
